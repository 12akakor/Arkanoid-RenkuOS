// Writes src/game/RomImage.cpp from a verified cartridge image.
//
//   tools/embed_rom.cpp build/arkanoid.rom src/game/RomImage.cpp
//
// The output is the ROM byte for byte, so nothing is interpreted or
// reordered; tests/rom_test.cpp checks the two against each other.
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include <string>
#include <vector>

#include "png.h"


namespace {

bool
ReadFile(const std::string& path, std::vector<uint8_t>& data)
{
	FILE* file = fopen(path.c_str(), "rb");
	if (file == NULL)
		return false;
	fseek(file, 0, SEEK_END);
	long size = ftell(file);
	fseek(file, 0, SEEK_SET);
	if (size <= 0) {
		fclose(file);
		return false;
	}
	data.resize(static_cast<size_t>(size));
	size_t read = fread(data.data(), 1, data.size(), file);
	fclose(file);
	return read == data.size();
}

}


int
main(int argc, char** argv)
{
	if (argc < 3) {
		fprintf(stderr, "usage: embed_rom <rom> <out.cpp>\n");
		return 1;
	}

	std::vector<uint8_t> rom;
	if (!ReadFile(argv[1], rom)) {
		fprintf(stderr, "cannot read %s\n", argv[1]);
		return 1;
	}
	if (rom.size() != 0x8000) {
		fprintf(stderr, "%s is %zu bytes, expected 32768\n", argv[1],
			rom.size());
		return 1;
	}

	FILE* out = fopen(argv[2], "w");
	if (out == NULL) {
		fprintf(stderr, "cannot write %s\n", argv[2]);
		return 1;
	}

	fprintf(out,
		"/*\n"
		" * Copyright 2026, Akakor.\n"
		" * All rights reserved. Distributed under the terms of the MIT"
		" License.\n"
		" */\n"
		"\n"
		"\n"
		"// Generated by tools/embed_rom.cpp from build/arkanoid.rom: the\n"
		"// original cartridge, byte for byte. Do not edit.\n"
		"#include \"RomImage.h\"\n"
		"\n"
		"\n"
		"const uint8_t kRomImage[kRomSize] = {\n");

	for (size_t i = 0; i < rom.size(); i += 12) {
		fprintf(out, "\t");
		size_t end = i + 12;
		if (end > rom.size())
			end = rom.size();
		for (size_t j = i; j < end; j++)
			fprintf(out, "0x%02x,%s", rom[j], j + 1 == end ? "" : " ");
		fprintf(out, "\t// 0x%04x\n", 0x4000 + static_cast<unsigned>(i));
	}

	fprintf(out, "};\n");
	fclose(out);

	uint32_t crc = png::Crc32Update(0xffffffffu, rom.data(), rom.size());
	printf("%s: 32768 bytes, crc32 %08x\n", argv[2], ~crc);
	return 0;
}
